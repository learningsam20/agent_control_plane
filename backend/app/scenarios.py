def persist_policies(db, blueprint: dict, scenario_id: str) -> list[str]:
    created: list[str] = []
    for p in blueprint.get("policies", []):
        existing = db.query(models.Policy).filter(models.Policy.name == p["name"]).first()
        if existing is not None:
            existing.description = p["description"]
            existing.effect = p["effect"]
            existing.actions = json.dumps(p["actions"])
            existing.conditions = json.dumps(p["conditions"])
            existing.order = p["order"]
            existing.enabled = True
            created.append(existing.name)
            continue
        policy = models.Policy(
            id=f"pol-{abs(hash(p['name'])) % 100000:05d}",
            name=p["name"], description=p["description"], effect=p["effect"],
            actions=json.dumps(p["actions"]), conditions=json.dumps(p["conditions"]),
            order=p["order"], enabled=True,
        )
        db.add(policy)
        created.append(policy.name)
    return created


def cleanup_lab_policies(db, scenario_id: str = "") -> int:
    q = db.query(models.Policy).filter(models.Policy.name.like("lab-%"))
    rows = q.all()
    count = len(rows)
    for row in rows:
        db.delete(row)
    return count


def restore_demo_agents(db) -> None:
    from .models import tier_for_score
    from .seed import DEMO_AGENTS

    for spec in DEMO_AGENTS:
        agent = db.get(models.Agent, spec["id"])
        if agent is None:
            continue
        agent.status = "active"
        agent.trust_score = spec["trust_score"]
        agent.tier = tier_for_score(spec["trust_score"])
        agent.granted_domains = json.dumps(spec["domains"])
        db.query(models.Violation).filter(models.Violation.agent_id == agent.id).delete(
            synchronize_session=False)


def reset_lab(db) -> dict:
    from .hashchain import append_event

    removed = cleanup_lab_policies(db)
    restore_demo_agents(db)
    append_event(db, "lab.reset", actor_id="console", subject="zero-trust-lab",
                 payload={"policies_removed": removed, "agents_restored": True},
                 decision="allow")
    db.commit()
    return {"policies_removed": removed, "agents_restored": True}
