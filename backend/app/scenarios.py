_AGENT_NAMES = {
    "ag_analyst": ["kay"],
    "ag_engineer": ["priya"],
    "ag_ml_engineer": ["leo"],
}
_AGENT_ROLE_IDS = {
    "ag_ml_engineer": ["ml-engineer", "ml_engineer", "ml engineer", "ml-engineers"],
    "ag_engineer": ["data-engineer", "data_engineer", "data engineer", "data-engineers"],
    "ag_analyst": ["analyst"],
}
_AGENT_ROLE_WORDS = {
    "ag_analyst": ["analyst"],
    "ag_ml_engineer": ["ml"],
    "ag_engineer": ["engineer"],
}


def _agent_matches(sentence: str) -> list[str]:
    lower = sentence.lower()
    found: list[str] = []
    # 1. proper names are decisive
    for aid, names in _AGENT_NAMES.items():
        if any(n in lower for n in names):
            found.append(aid)
    # 2. hyphenated roles; consume matched phrases so a bare role word such as
    #    "engineer" can't be matched again inside "ml-engineer"
    remaining = lower
    for aid, roles in _AGENT_ROLE_IDS.items():
        if aid in found or not any(r in lower for r in roles):
            continue
        found.append(aid)
        for r in roles:
            remaining = remaining.replace(r, " ")
    # 3. bare role words on the residual text
    for aid, roles in _AGENT_ROLE_WORDS.items():
        if aid not in found and any(r in remaining for r in roles):
            found.append(aid)
    return found


def _parse_agents(objective: str, agents_hint: list[str] | None) -> list[str]:
    ids: list[str] = []
    for a in agents_hint or []:
        if a not in ids:
            ids.append(a)
    for aid in _agent_matches(objective):
        if aid not in ids:
            ids.append(aid)
    return ids or ["ag_analyst"]


def _role(agent_id: str) -> str:
    from agents.registry import get_agent_spec

    try:
        return get_agent_spec(agent_id)["role"]
    except (KeyError, Exception):  # noqa: BLE001
        return {"ag_analyst": "analyst", "ag_engineer": "engineer", "ag_ml_engineer": "ml_engineer"}.get(agent_id, "analyst")


def _catalog(db) -> list[dict]:
    rows = db.query(models.DataHubEntity).all()
    return [
        {"urn": e.urn, "name": e.name, "domain": e.domain,
         "data_classification": e.data_classification, "description": e.description}
        for e in rows
    ]


def _pick_agent(sentence: str, agents: list[str]) -> str:
    for aid in _agent_matches(sentence):
        if aid in agents:
            return aid
    return agents[0]


_MATCH_STOP = {"from", "for", "into", "via", "main", "the", "a", "an", "to", "of", "in", "on", "with", "and", "or"}


def _norm_token(w: str) -> str:
    w = w.lower()
    if len(w) > 3 and w.endswith("ies"):
        return w[:-3] + "y"
    if len(w) > 3 and w.endswith("s") and not w.endswith("ss"):
        return w[:-1]
    return w


def _match_tokens(text: str) -> set[str]:
    from agents.planner import _tokens

    return {_norm_token(t) for t in _tokens(text) if _norm_token(t) not in _MATCH_STOP}


def _match_entity_local(objective: str, entities: list[dict], domains: list[str]) -> str | None:
    """Catalog match that weights the entity NAME over its description, with
    singular/plural normalization and noise-word removal, so a sentence about
    "raw patient records" picks ``raw_patients`` rather than a view whose name
    merely shares a generic word like ``from``."""
    words = _match_tokens(objective)
    best, best_score = None, 0
    for ent in entities:
        name = _match_tokens(ent["name"])
        desc = _match_tokens(f"{ent.get('description', '')} {ent.get('domain', '')}")
        overlap = len(words & name) * 3 + len(words & desc)
        if ent.get("domain") in domains:
            overlap += 1
        if overlap > best_score:
            best, best_score = ent["urn"], overlap
    return best if best_score >= 3 else None


def _rule_steps(db, objective: str, agents: list[str]) -> list[dict]:
    from agents.planner import _action_type, _ROLE_DEFAULT

    entities = _catalog(db)
    sentences = [s.strip() for s in re.split(r"[.;\n]+", objective) if s.strip()]
    if not sentences:
        sentences = [objective]
    steps: list[dict] = []
    seen: set[tuple] = set()
    for s in sentences:
        agent = _pick_agent(s, agents)
        role = _role(agent)
        action = _action_type(s, role)
        urn = _match_entity_local(s, entities, _domains(agent)) or _ROLE_DEFAULT.get(role)
        ent = db.get(models.DataHubEntity, urn)
        key = (agent, action, urn)
        if key in seen:
            continue
        seen.add(key)
        steps.append({
            "agent": agent, "action": action, "resource": urn,
            "domain": ent.domain if ent else "",
            "classification": ent.data_classification if ent else "public",
            "note": s[:160],
        })
    return steps


def _domains(agent_id: str) -> list[str]:
    from agents.registry import get_agent_spec

    try:
        return get_agent_spec(agent_id)["domains"]
    except (KeyError, Exception):  # noqa: BLE001
        return []


def _llm_steps(db, objective: str, agents: list[str]) -> list[dict] | None:
    """Best-effort LLM step extraction; None degrades to the rule translator."""
    if not settings.llm_model:
        return None
    try:
        import litellm

        entities = _catalog(db)
        catalog = "\n".join(
            f"- URN {e['urn']} | name: {e.get('name', '')} | domain: {e.get('domain', '')} | "
            f"classification: {e.get('data_classification', 'public')}"
            for e in entities[:60]
        )
        system = (
            "You extract governed agent actions from a scenario. The ONLY resources "
            "are the catalog items below; you MUST use their exact URNs.\n\n"
            "{catalog}\n\n"
            'Return ONLY JSON: {{"steps": [{{"agent": "<agent id from {agents}>", '
            '"action": "<read|query|transform|write|ingest|deploy>", '
            '"resource": "<exact catalog URN>", "note": "<one-line rationale>"}}]}}.'.format(
                catalog=catalog, agents=agents)
        )
        user = f"Scenario: {objective}"
        resp = litellm.completion(
            model=settings.llm_model,
            messages=[{"role": "system", "content": system}, {"role": "user", "content": user}],
            api_base=settings.llm_base_url or None,
            api_key=settings.llm_api_key or None,
            temperature=settings.llm_temperature,
            timeout=30,
        )
        text = resp.choices[0].message.content or ""
        start, end = text.find("{"), text.rfind("}")
        if start == -1 or end <= start:
            return None
        payload = json.loads(text[start:end + 1])
        raw_steps = payload.get("steps", [])
        valid = [s for s in raw_steps if isinstance(s, dict)]
        steps = []
        urns = {e["urn"] for e in entities}
        for s in valid[:8]:
            agent = s.get("agent", "")
            action = s.get("action", "")
            resource = s.get("resource", "")
            if agent not in agents or action not in models.ACTION_TYPES or resource not in urns:
                continue
            ent = db.get(models.DataHubEntity, resource)
            steps.append({
                "agent": agent, "action": action, "resource": resource,
                "domain": ent.domain if ent else "",
                "classification": ent.data_classification if ent else "public",
                "note": (s.get("note") or "")[:160],
            })
        return steps or None
    except Exception:  # noqa: BLE001
        return None


def _derive_policies(steps: list[dict]) -> list[dict]:
    policies: list[dict] = []
    actions = {s["action"] for s in steps}
    if any(s.get("classification") == "restricted" for s in steps):
        policies.append(_policy("lab-allow-delegated-restricted-read"))
        policies.append(_policy("lab-require-delegation-for-restricted"))
    if "transform" in actions:
        policies.append(_policy("lab-deny-pii-transforms-below-elevated"))
        policies.append(_policy("lab-allow-transform-sensitive-elevated"))
    if "deploy" in actions:
        policies.append(_policy("lab-allow-deploy-ml-models"))
        policies.append(_policy("lab-deny-deploy-below-elevated"))
    return policies


def _derive_delegation(objective: str, steps: list[dict]) -> dict | None:
    if "delegat" not in objective.lower():
        return None
    restricted = [s for s in steps if s.get("classification") == "restricted"]
    datasets = [s["resource"] for s in restricted] or [s["resource"] for s in steps[:1]]
    return {
        "delegator_id": "ag_engineer", "delegatee_id": "ag_analyst",
        "scope": {"actions": ["read", "query"], "datasets": datasets, "domains": []},
        "max_depth": 1,
    }


def _flag_delegated_steps(steps: list[dict], delegation: dict | None) -> list[dict]:
    if not delegation:
        return steps
    scope = delegation["scope"]
    actions = scope.get("actions", [])
    datasets = set(scope.get("datasets", []))
    delegatee = delegation["delegatee_id"]
    for s in steps:
        if s["agent"] == delegatee and s["resource"] in datasets and s["action"] in actions:
            s["delegation"] = True
    return steps


def _custom_blueprint(db, objective: str, agents_hint: list[str] | None) -> dict:
    agents = _parse_agents(objective, agents_hint)
    steps = _llm_steps(db, objective, agents) or _rule_steps(db, objective, agents)
    policies = _derive_policies(steps)
    delegation = _derive_delegation(objective, steps)
    steps = _flag_delegated_steps(steps, delegation)
    return {"agents": agents, "steps": steps, "policies": policies, "delegation": delegation}


def transform(db, scenario_id: str = "", objective: str = "", agents_hint: list[str] | None = None) -> dict:
    """Transform a scenario (predefined or free text) into a proposed plan."""
    if scenario_id:
        scenario = get_predefined(scenario_id)
        if scenario is None:
            raise ValueError(f"unknown scenario: {scenario_id}")
        for step in scenario["blueprint"]["steps"]:
            if db.get(models.DataHubEntity, step["resource"]) is None:
                raise ValueError(
                    f"scenario {scenario_id} references {step['resource']} which is not in the catalog")
        blueprint = dict(scenario["blueprint"])
        blueprint.setdefault("agents", list(scenario.get("agents") or []))
        name = scenario["name"]
        effective_objective = scenario["objective"]
    else:
        if not objective or not objective.strip():
            raise ValueError("a custom scenario requires an objective")
        blueprint = _custom_blueprint(db, objective, agents_hint)
        name = objective.strip()[:64]
        effective_objective = objective.strip()

    plan = models.ScenarioPlan(
        id=f"plan-{int(time.time_ns()) % 10**14}",
        scenario_id=scenario_id, name=name, objective=effective_objective,
        status="proposed", blueprint=json.dumps(blueprint),
    )
    db.add(plan)
    db.commit()
    db.refresh(plan)
    return {"plan_id": plan.id, "name": plan.name, "status": plan.status,
            "scenario_id": plan.scenario_id, "blueprint": blueprint}


