def _policy_dicts(db) -> list[dict]:
    rows = db.query(models.Policy).filter(models.Policy.enabled.is_(True)).all()
    return [
        {"name": p.name, "effect": p.effect, "actions": json.loads(p.actions or "[]"),
         "conditions": json.loads(p.conditions or "[]"), "order": p.order, "generated": False}
        for p in rows
    ]


def _proposed_policy_dicts(blueprint: dict) -> list[dict]:
    return [
        {"name": p["name"], "effect": p["effect"], "actions": p["actions"],
         "conditions": p["conditions"], "order": p["order"], "generated": True}
        for p in blueprint.get("policies", [])
    ]


def _simulate_input(db, agent, action_type: str, resource: str, delegation_spec: dict | None) -> dict:
    entity = db.get(models.DataHubEntity, resource)
    granted = json.loads(agent.granted_domains or "[]")
    effective_tier = agent.tier
    delegator_id = ""
    delegation_active = bool(delegation_spec)
    depth, max_depth = 0, 0
    dataset_scope_match, action_in_scope = False, True
    if delegation_spec:
        delegator = db.get(models.Agent, delegation_spec.get("delegator_id", ""))
        if delegator is not None:
            effective_tier = delegator.tier
            delegator_id = delegator.id
        scope = delegation_spec.get("scope", {})
        granted = list(dict.fromkeys(granted + scope.get("domains", [])))
        max_depth = delegation_spec.get("max_depth", 1)
        depth = delegation_spec.get("depth", 0)
        action_in_scope = action_type in scope.get("actions", [])
        datasets = scope.get("datasets", [])
        dataset_scope_match = bool(datasets) and resource in datasets
    return {
        "agent": {"id": agent.id, "reputation_tier": effective_tier, "trust_score": agent.trust_score,
                  "status": agent.status, "granted_domains": granted},
        "action": {"type": action_type, "resource": resource},
        "target": {
            "entity_type": entity.type if entity else "dataset",
            "domain": entity.domain if entity else "",
            "data_classification": entity.data_classification if entity else "public",
            "owner_team": entity.owner_team if entity else "",
        },
        "delegation": {
            "active": delegation_active, "depth": depth, "max_depth": max_depth,
            "delegator_id": delegator_id, "dataset_scope_match": dataset_scope_match,
            "action_in_scope": action_in_scope,
        },
    }


def _evaluate_policy_dicts(policy_dicts: list[dict], input_data: dict) -> dict:
    for p in sorted(policy_dicts, key=lambda p: p["order"]):
        actions = p.get("actions") or []
        if actions and input_data["action"]["type"] not in actions:
            continue
        conditions = p.get("conditions") or []
        if conditions and not all(condition_matches(c, input_data) for c in conditions):
            continue
        return {"allow": p["effect"] == "allow", "reason": p["name"],
                "policy": p["name"], "generated": p.get("generated", False)}
    return {"allow": False, "reason": "no matching policy (default deny)",
            "policy": "default-deny", "generated": False}


def preview(db, plan: models.ScenarioPlan) -> dict:
    """Simulate the enforced decisions for every step using the seed policies
    plus the proposed lab policies — all in memory, nothing written."""
    blueprint = json.loads(plan.blueprint)
    policy_dicts = _policy_dicts(db) + _proposed_policy_dicts(blueprint)
    delegation_spec = blueprint.get("delegation")

    predictions = []
    for idx, step in enumerate(blueprint.get("steps", [])):
        agent = db.get(models.Agent, step["agent"])
        spec = delegation_spec if step.get("delegation") else None
        if agent is None:
            predictions.append({"index": idx, "error": f"unknown agent {step['agent']}"})
            continue
        input_data = _simulate_input(db, agent, step["action"], step["resource"], spec)
        # Mirror the gateway's delegation scope gate, which precedes policy.
        if spec and not input_data["delegation"]["action_in_scope"]:
            decision = {"allow": False, "reason": f"action outside delegated scope: {step['action']}",
                        "policy": "delegation.scope", "generated": False}
        else:
            decision = _evaluate_policy_dicts(policy_dicts, input_data)
        entity = db.get(models.DataHubEntity, step["resource"])
        predictions.append({
            "index": idx,
            "agent": step["agent"], "action": step["action"], "resource": step["resource"],
            "resource_name": entity.name if entity else step["resource"],
            "domain": step.get("domain") or (entity.domain if entity else ""),
            "classification": step.get("classification") or (entity.data_classification if entity else ""),
            "delegation": bool(step.get("delegation")),
            "note": step.get("note", ""),
            "expected": step.get("expect"),
            "predicted": "allow" if decision["allow"] else "deny",
            "reason": decision["reason"], "policy": decision["policy"],
            "policy_generated": decision["generated"],
        })

    return {"plan_id": plan.id, "status": plan.status, "predictions": predictions,
            "proposed_policies": blueprint.get("policies", []),
            "delegation": blueprint.get("delegation")}


