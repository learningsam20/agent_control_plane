"""Zero-Trust Lab scenario engine.

A scenario is a natural-language situation ("analyst blocked from restricted
billing, engineer delegates scoped read"). The planner transforms it into a
concrete blueprint: agentic steps ``{agent, action, resource}``, generated
governance policies, and an optional delegation. Blueprints are staged as
``ScenarioPlan`` rows (status ``proposed``), previewed against an in-memory
policy evaluation that persists nothing, and only after explicit approval are
the generated policies created in the store and the steps enforced through the
signed gateway.
"""

